SELECT 
 p.PUBLISHER, 
AVG(p.PRICE) AS AVG_PRICE, 
 SUM(l.HOURSPLAYED) AS TOTAL_HOURS 
FROM PRODUCTLIST p 
INNER JOIN 
USERLIBRARY l ON p.PRODUCTCODE = l.PRODUCTCODE 
GROUP BY 
p.PUBLISHER;


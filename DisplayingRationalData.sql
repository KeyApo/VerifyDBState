TRUNC(MONTHS_BETWEEN(SYSDATE, u.BIRTHDAY) /12) AS AGE, 
o.ORDERID, 
o.PRODUCTCODE 
FROM USERBASE u 
FULL JOIN ORDERS o 
ON u.USERID= o.USERID 

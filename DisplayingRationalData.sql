-- Question 22
SELECT  
u.USERID, 
u.USERNAME, 
u.EMAIL, 
COALESCE(SUM(c.SEVERITYPOINT), 0) AS TOTAL_SEVERITY 
FROM  
USERBASE u 
LEFT JOIN  
INFRACTIONS i ON u.USERID = i.USERID 
LEFT JOIN 
COMMUNITYRULES c ON i.RULENUM = c.RULENUM 
GROUP BY  
u.USERID, 
u.USERNAME, 
u.EMAIL 
ORDER BY 
TOTAL_SEVERITY DESC;


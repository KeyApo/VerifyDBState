CREATE VIEW Product_Reviews AS 
SELECT 
p.PRODUCTNAME, p.GENRE, r.RATING 
FROM REVIEWS r 
INNER JOIN 
PRODUCTLIST p ON r.PRODUCTCODE = p.PRODUCTCODE 
WHERE 
r.RATING <= 5 
ORDER BY 
r.RATING ASC;


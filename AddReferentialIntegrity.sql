SELECT CONCAT(FIRSTNAME, ' ', LASTNAME) AS FULLNAME, BIRTHDAY, FLOOR(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) AS AGE 
FROM USERBASE 
GROUP BY FIRSTNAME, LASTNAME, USERNAME, BIRTHDAY 
HAVING FLOOR(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) >= 18 
ORDER BY FIRSTNAME ASC;

